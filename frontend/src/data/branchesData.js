export function searchNearestBranches(rawQuery = "", userCoordinates = null) {
  const query = (rawQuery || "").trim().toLowerCase();

  // 1. If explicit user coordinates provided (from GPS geolocation)
  if (userCoordinates && typeof userCoordinates.lat === "number" && typeof userCoordinates.lng === "number") {
    const isFarFromJaipur =
      calculateStraightDistanceKm(
        userCoordinates.lat,
        userCoordinates.lng,
        JAIPUR_CENTER_COORDINATES.lat,
        JAIPUR_CENTER_COORDINATES.lng
      ) > 55;

    const ranked = BRANCHES_DATA.map((branch) => {
      const straightKm = calculateStraightDistanceKm(
        userCoordinates.lat,
        userCoordinates.lng,
        branch.coordinates.lat,
        branch.coordinates.lng
      );
      const roadKm = estimateRoadDistanceKm(straightKm);
      const travelMins = estimateTravelTimeMinutes(roadKm);

      return {
        ...branch,
        straightDistanceKm: straightKm,
        distanceKm: roadKm,
        travelTime: formatTravelTime(travelMins),
        travelMinutes: travelMins,
      };
    }).sort((a, b) => a.distanceKm - b.distanceKm);

    return {
      status: "success",
      queryType: "geolocation",
      userLocationName: isFarFromJaipur ? "Your Current GPS Location (Outside Jaipur)" : "Your Current Location (Jaipur)",
      isOutsideJaipur: isFarFromJaipur,
      outsideInfo: isFarFromJaipur
        ? {
            detectedPlace: "Outside Jaipur",
            distanceToJaipur: `${Math.round(ranked[0].distanceKm)} km`,
            note: "You are currently outside Jaipur. ThirdEye's flagship offline campuses are in Jaipur. We offer verified hostel facilities, weekend hybrid batches, and online live classes!",
          }
        : null,
      nearestBranch: ranked[0],
      branches: ranked,
    };
  }

  // 2. Default state: No query entered
  if (!query) {
    const defaultRanked = BRANCHES_DATA.map((b) => ({
      ...b,
      distanceKm: null,
      travelTime: null,
    }));
    return {
      status: "default",
      queryType: "all",
      userLocationName: "All Jaipur Branches",
      isOutsideJaipur: false,
      outsideInfo: null,
      nearestBranch: defaultRanked[0],
      branches: defaultRanked,
    };
  }

  // 3. Check if query is a 6-digit Indian PIN Code
  const cleanPin = query.replace(/\D/g, "");
  if (cleanPin.length === 6) {
    // A) Known Jaipur PIN Code
    if (JAIPUR_PINCODES_MAP[cleanPin]) {
      const pinInfo = JAIPUR_PINCODES_MAP[cleanPin];
      const ranked = BRANCHES_DATA.map((branch) => {
        const straightKm = calculateStraightDistanceKm(
          pinInfo.lat,
          pinInfo.lng,
          branch.coordinates.lat,
          branch.coordinates.lng
        );
        const roadKm = estimateRoadDistanceKm(straightKm);
        const travelMins = estimateTravelTimeMinutes(roadKm);

        return {
          ...branch,
          straightDistanceKm: straightKm,
          distanceKm: roadKm,
          travelTime: formatTravelTime(travelMins),
          travelMinutes: travelMins,
          isExactPincodeMatch: branch.coveredPincodes.includes(cleanPin),
        };
      }).sort((a, b) => a.distanceKm - b.distanceKm);

      return {
        status: "success",
        queryType: "pincode",
        userLocationName: `PIN ${cleanPin} (${pinInfo.locality})`,
        isOutsideJaipur: false,
        outsideInfo: null,
        nearestBranch: ranked[0],
        branches: ranked,
      };
    }

    // B) Other Jaipur PIN Code (Starts with 302xxx but not in map)
    if (cleanPin.startsWith("302")) {
      const ranked = BRANCHES_DATA.map((branch) => {
        const straightKm = calculateStraightDistanceKm(
          JAIPUR_CENTER_COORDINATES.lat,
          JAIPUR_CENTER_COORDINATES.lng,
          branch.coordinates.lat,
          branch.coordinates.lng
        );
        const roadKm = estimateRoadDistanceKm(straightKm);
        return {
          ...branch,
          distanceKm: roadKm,
          travelTime: formatTravelTime(estimateTravelTimeMinutes(roadKm)),
        };
      }).sort((a, b) => a.distanceKm - b.distanceKm);

      return {
        status: "success",
        queryType: "pincode",
        userLocationName: `Jaipur Region PIN ${cleanPin}`,
        isOutsideJaipur: false,
        outsideInfo: null,
        nearestBranch: ranked[0],
        branches: ranked,
      };
    }

    // C) Outside Jaipur PIN Code (Non-302xxx)
    const pinPrefix3 = cleanPin.substring(0, 3);
    let detectedStateCity = "Outside Jaipur";
    let approxDistance = 250;

    if (pinPrefix3 === "305") {
      detectedStateCity = "Ajmer District, Rajasthan";
      approxDistance = 135;
    } else if (pinPrefix3 === "332") {
      detectedStateCity = "Sikar District, Rajasthan";
      approxDistance = 115;
    } else if (pinPrefix3 === "301") {
      detectedStateCity = "Alwar District, Rajasthan";
      approxDistance = 145;
    } else if (pinPrefix3 === "324") {
      detectedStateCity = "Kota District, Rajasthan";
      approxDistance = 240;
    } else if (pinPrefix3 === "342") {
      detectedStateCity = "Jodhpur District, Rajasthan";
      approxDistance = 330;
    } else if (cleanPin.startsWith("110")) {
      detectedStateCity = "Delhi NCR";
      approxDistance = 265;
    } else if (cleanPin.startsWith("122")) {
      detectedStateCity = "Gurugram, Haryana";
      approxDistance = 230;
    } else if (cleanPin.startsWith("400")) {
      detectedStateCity = "Mumbai, Maharashtra";
      approxDistance = 1150;
    }

    const outsideBranches = BRANCHES_DATA.map((branch) => ({
      ...branch,
      distanceKm: approxDistance,
      travelTime: `${Math.round(approxDistance / 65)} hrs drive`,
    }));

    return {
      status: "success",
      queryType: "pincode_outside",
      userLocationName: `PIN ${cleanPin} (${detectedStateCity})`,
      isOutsideJaipur: true,
      outsideInfo: {
        detectedPlace: detectedStateCity,
        pincode: cleanPin,
        distanceToJaipur: `~${approxDistance} km`,
        note: `You searched PIN ${cleanPin} located in ${detectedStateCity}. All ThirdEye physical classroom centers are located in Jaipur. We offer student hostel arrangements, intensive bootcamps, and live online batches!`,
      },
      nearestBranch: outsideBranches[0], // Sanganer Flagship
      branches: outsideBranches,
    };
  }

  // 4. Check if query matches major External Cities (Outside Jaipur)
  const matchedExtCity = MAJOR_EXTERNAL_CITIES.find(
    (c) =>
      query.includes(c.name.toLowerCase()) ||
      c.name.toLowerCase().includes(query)
  );

  if (matchedExtCity) {
    const ranked = BRANCHES_DATA.map((branch) => ({
      ...branch,
      distanceKm: matchedExtCity.approxKm,
      travelTime: `${Math.round(matchedExtCity.approxKm / 60)} hrs (${matchedExtCity.highway})`,
    }));

    return {
      status: "success",
      queryType: "outside_city",
      userLocationName: `${matchedExtCity.name}, ${matchedExtCity.state}`,
      isOutsideJaipur: true,
      outsideInfo: {
        detectedPlace: `${matchedExtCity.name}, ${matchedExtCity.state}`,
        distanceToJaipur: `~${matchedExtCity.approxKm} km`,
        highway: matchedExtCity.highway,
        note: `Visiting us from ${matchedExtCity.name}? Our Flagship campus is ~${matchedExtCity.approxKm} km via ${matchedExtCity.highway}. We offer dedicated student hostel & PG tie-ups right across from our campus!`,
      },
      nearestBranch: ranked[0],
      branches: ranked,
    };
  }

  // 5. Check if query matches a specific branch name, served locality, or landmark
  let bestMatchedBranch = null;
  let matchLocalityName = "";

  for (const branch of BRANCHES_DATA) {
    // Direct name match
    if (
      branch.name.toLowerCase().includes(query) ||
      branch.shortName.toLowerCase().includes(query) ||
      branch.zone.toLowerCase().includes(query)
    ) {
      bestMatchedBranch = branch;
      matchLocalityName = branch.shortName;
      break;
    }

    // Served locality match
    const matchedLocality = branch.servedLocalities.find(
      (loc) => loc.toLowerCase().includes(query) || query.includes(loc.toLowerCase())
    );
    if (matchedLocality) {
      bestMatchedBranch = branch;
      matchLocalityName = matchedLocality;
      break;
    }
  }

  // 6. Check locality across all known PIN codes
  if (!bestMatchedBranch) {
    for (const [pin, info] of Object.entries(JAIPUR_PINCODES_MAP)) {
      if (info.locality.toLowerCase().includes(query)) {
        // Calculate nearest branch to this pin coordinate
        const ranked = BRANCHES_DATA.map((branch) => {
          const straightKm = calculateStraightDistanceKm(
            info.lat,
            info.lng,
            branch.coordinates.lat,
            branch.coordinates.lng
          );
          const roadKm = estimateRoadDistanceKm(straightKm);
          return {
            ...branch,
            distanceKm: roadKm,
            travelTime: formatTravelTime(estimateTravelTimeMinutes(roadKm)),
          };
        }).sort((a, b) => a.distanceKm - b.distanceKm);

        return {
          status: "success",
          queryType: "locality",
          userLocationName: `${info.locality} (PIN ${pin})`,
          isOutsideJaipur: false,
          outsideInfo: null,
          nearestBranch: ranked[0],
          branches: ranked,
        };
      }
    }
  }

  // If a branch or locality was found directly
  if (bestMatchedBranch) {
    const originLat = bestMatchedBranch.coordinates.lat;
    const originLng = bestMatchedBranch.coordinates.lng;

    const ranked = BRANCHES_DATA.map((branch) => {
      const isTarget = branch.id === bestMatchedBranch.id;
      const straightKm = isTarget
        ? 0.4
        : calculateStraightDistanceKm(
            originLat,
            originLng,
            branch.coordinates.lat,
            branch.coordinates.lng
          );
      const roadKm = isTarget ? 0.5 : estimateRoadDistanceKm(straightKm);
      const travelMins = isTarget ? 3 : estimateTravelTimeMinutes(roadKm);

      return {
        ...branch,
        distanceKm: roadKm,
        travelTime: isTarget ? "Walking distance (2-3 mins)" : formatTravelTime(travelMins),
        travelMinutes: travelMins,
        isDirectMatch: isTarget,
      };
    }).sort((a, b) => a.distanceKm - b.distanceKm);

    return {
      status: "success",
      queryType: "locality",
      userLocationName: `${matchLocalityName}, Jaipur`,
      isOutsideJaipur: false,
      outsideInfo: null,
      nearestBranch: ranked[0],
      branches: ranked,
    };
  }

  // 7. General search fallback (matches address, description, or landmark substrings)
  const filtered = BRANCHES_DATA.filter(
    (b) =>
      b.address.toLowerCase().includes(query) ||
      b.landmark.toLowerCase().includes(query) ||
      b.tag.toLowerCase().includes(query) ||
      b.popularCourses.some((c) => c.toLowerCase().includes(query))
  );

  if (filtered.length > 0) {
    const ranked = filtered.map((b) => ({
      ...b,
      distanceKm: null,
      travelTime: null,
    }));

    return {
      status: "success",
      queryType: "keyword",
      userLocationName: `Search: "${rawQuery}"`,
      isOutsideJaipur: false,
      outsideInfo: null,
      nearestBranch: ranked[0],
      branches: ranked,
    };
  }

  // 8. If totally unknown search, treat as potential outer region
  const defaultList = BRANCHES_DATA.map((b) => ({
    ...b,
    distanceKm: null,
    travelTime: null,
  }));

  return {
    status: "no_direct_match",
    queryType: "unknown",
    userLocationName: `"${rawQuery}"`,
    isOutsideJaipur: true,
    outsideInfo: {
      detectedPlace: rawQuery,
      distanceToJaipur: "Varies",
      note: `"${rawQuery}" was not found inside municipal Jaipur limits. Showing all Jaipur campuses. We welcome students from all across India with dedicated hostel assistance & online hybrid courses!`,
    },
    nearestBranch: defaultList[0],
    branches: defaultList,
  };
}

// Generate Google Maps Directions URL
export function getGoogleMapsDirectionsUrl(originTextOrCoords, branch) {
  const dest = `${branch.coordinates.lat},${branch.coordinates.lng}`;
  if (!originTextOrCoords) {
    return `https://www.google.com/maps/dir/?api=1&destination=${dest}&travelmode=driving`;
  }
  if (typeof originTextOrCoords === "object" && originTextOrCoords.lat) {
    return `https://www.google.com/maps/dir/?api=1&origin=${originTextOrCoords.lat},${originTextOrCoords.lng}&destination=${dest}&travelmode=driving`;
  }
  return `https://www.google.com/maps/dir/?api=1&origin=${encodeURIComponent(originTextOrCoords + ", Jaipur")}&destination=${dest}&travelmode=driving`;
}

// Generate embed map URL for an iframe
export function getGoogleMapsEmbedUrl(branch, originQuery = "") {
  if (originQuery && originQuery.trim()) {
    const origin = encodeURIComponent(originQuery.trim() + ", Jaipur");
    const dest = `${branch.coordinates.lat},${branch.coordinates.lng}`;
    return `https://maps.google.com/maps?saddr=${origin}&daddr=${dest}&hl=en&z=13&output=embed`;
  }
  return `https://maps.google.com/maps?q=${branch.coordinates.lat},${branch.coordinates.lng}&hl=en&z=15&output=embed`;
}
