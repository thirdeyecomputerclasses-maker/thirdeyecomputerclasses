// Haversine geodesic distance in kilometers
export function calculateStraightDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

// Convert straight flight distance to realistic urban/highway road kilometers
export function estimateRoadDistanceKm(straightKm) {
  if (straightKm <= 0.5) return 0.6;
  if (straightKm < 15) {
    // City streets winding factor ~1.28
    return Math.round(straightKm * 1.28 * 10) / 10;
  }
  if (straightKm < 50) {
    // Sub-urban arterial factor ~1.22
    return Math.round(straightKm * 1.22 * 10) / 10;
  }
  // Highway factor ~1.15
  return Math.round(straightKm * 1.15);
}

// Estimate realistic driving time in minutes
export function estimateTravelTimeMinutes(roadKm) {
  if (roadKm <= 1) return 4;
  if (roadKm <= 10) {
    // ~22 km/h average city traffic + traffic lights
    return Math.round((roadKm / 22) * 60) + 3;
  }
  if (roadKm <= 35) {
    // ~35 km/h ring road / bypass
    return Math.round((roadKm / 35) * 60) + 5;
  }
  // Highway ~70 km/h
  return Math.round((roadKm / 70) * 60);
}

// Format travel time string nicely (e.g., "14 mins" or "2 hrs 15 mins")
export function formatTravelTime(minutes) {
  if (minutes < 60) {
    return `${minutes} mins`;
  }
  const hrs = Math.floor(minutes / 60);
  const mins = minutes % 60;
  return mins > 0 ? `${hrs} hr ${mins} mins` : `${hrs} hrs`;
}

